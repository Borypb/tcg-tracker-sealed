import csv, io, json, re, sys, urllib.request
from pathlib import Path

CSV = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv"
local = Path("/tmp/claude-0/species.csv")
text = local.read_text() if local.exists() else urllib.request.urlopen(CSV).read().decode()
en, fr = {}, {}
for row in csv.reader(io.StringIO(text)):
    if len(row) < 3 or not row[0].isdigit():
        continue
    if row[1] == "9": en[row[2]] = row[0]
    if row[1] == "5": fr[row[0]] = row[2]
SPECIES = {name: fr[i] for name, i in en.items() if i in fr}

def sp(s):
    def rep(m):
        n = m.group(1)
        if n not in SPECIES:
            sys.exit(f"Espèce inconnue : {n}")
        return SPECIES[n]
    return re.sub(r"\{([^}]+)\}", rep, s)

